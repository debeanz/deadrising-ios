// xfb2xenos: converts the Xbox 360 shader containers in Dead Rising's MT Framework shader
// packages (XDK 2006 compiler, flags 0x102A0Exx) into the 2008 layout XenosRecomp reads
// (flags 0x102A11xx). Only the wrapper changes: constant table, definitions and microcode are
// copied as they are. Layout findings: docs/shaders.md.
//
// Usage: xfb2xenos <output dir> <input file or dir>...

#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <filesystem>
#include <fstream>
#include <string>
#include <vector>

#define XXH_INLINE_ALL
#include "../tools/XenosRecomp/thirdparty/xxHash/xxhash.h"

namespace fs = std::filesystem;

// Listing of every converted shader, keyed by the hash XenosRecomp uses for its cache entries and
// its failed/ folder: source file and offset, 2006 header and shader header words, definitions.
static FILE* g_listing = nullptr;
static std::string g_currentFile;

// Game-side shader key: what the runtime hashes when D3D initialises a shader object
// (runtime/src/gpu/shaders.cpp, ShaderKey there must stay identical): the 2006 container's virtual
// part, then the microcode, as they are in the file and in guest memory.
static uint64_t ShaderKey(const uint8_t* container, size_t virtualSize, const uint8_t* microcode, size_t physicalSize)
{
    return XXH3_64bits_withSeed(microcode, physicalSize, XXH3_64bits(container, virtualSize));
}

static std::vector<std::pair<uint64_t, uint64_t>> g_keys; // { game-side key, XenosRecomp cache hash }

static void WriteKeyTable(const fs::path& path)
{
    std::sort(g_keys.begin(), g_keys.end());
    g_keys.erase(std::unique(g_keys.begin(), g_keys.end()), g_keys.end());

    FILE* f = fopen(path.string().c_str(), "w");
    fprintf(f, "// Generated by xfb2xenos: game-side shader key -> XenosRecomp shader cache hash.\n");
    fprintf(f, "#include \"shader_keys.h\"\n\n");
    fprintf(f, "const ShaderKey g_shaderKeys[] =\n{\n");
    for (auto& [key, hash] : g_keys)
        fprintf(f, "    { 0x%016llXull, 0x%016llXull },\n", (unsigned long long)key, (unsigned long long)hash);
    fprintf(f, "};\n\nconst size_t g_shaderKeyCount = %zu;\n", g_keys.size());
    fclose(f);
}

static uint32_t Get(const std::vector<uint8_t>& d, size_t o)
{
    return o + 4 <= d.size() ? (uint32_t(d[o]) << 24 | uint32_t(d[o + 1]) << 16 | uint32_t(d[o + 2]) << 8 | d[o + 3]) : 0;
}

static void Put(std::vector<uint8_t>& d, uint32_t v)
{
    d.push_back(uint8_t(v >> 24));
    d.push_back(uint8_t(v >> 16));
    d.push_back(uint8_t(v >> 8));
    d.push_back(uint8_t(v));
}

static void Set(std::vector<uint8_t>& d, size_t o, uint32_t v)
{
    d[o] = uint8_t(v >> 24);
    d[o + 1] = uint8_t(v >> 16);
    d[o + 2] = uint8_t(v >> 8);
    d[o + 3] = uint8_t(v);
}

static void Align(std::vector<uint8_t>& d, size_t a)
{
    while (d.size() % a)
        d.push_back(0);
}

struct Stats
{
    int pixel = 0, vertex = 0, skipped = 0, vpos = 0, intDefs = 0, loopDefs = 0, syntheticTables = 0;
};

// Most of Dead Rising's shaders were compiled without a constant table (no reflection data).
// XenosRecomp maps constants by register number, so a table that declares every register works:
// one float4 array over the whole range, samplers 0-15 and bools 0-15. Standard D3DX layout
// (D3DXSHADER_CONSTANTTABLE), offsets relative to the table start.
static std::vector<uint8_t> BuildSyntheticConstantTable(bool isPixel)
{
    struct Entry { std::string name; uint16_t set, index, count; uint32_t typeOffset; };
    std::vector<Entry> entries;
    entries.push_back({ isPixel ? "g_PsConstants" : "g_VsConstants", 2 /* Float4 */, 0, uint16_t(isPixel ? 224 : 256), 0 });
    for (uint16_t i = 0; i < 32; i++)
        entries.push_back({ "g_Sampler" + std::to_string(i), 3 /* Sampler */, i, 1, 0 });
    for (uint16_t i = 0; i < 16; i++)
        entries.push_back({ "g_Bool" + std::to_string(i), 0 /* Bool */, i, 1, 0 });

    const uint32_t infoOffset = 0x1C;
    const uint32_t typesOffset = infoOffset + uint32_t(entries.size()) * 0x14;
    const uint32_t floatType = typesOffset, samplerType = typesOffset + 0x10, boolType = typesOffset + 0x20;
    uint32_t stringOffset = typesOffset + 0x30;

    std::vector<uint8_t> t(stringOffset, 0);
    std::vector<uint32_t> nameOffsets;
    for (auto& e : entries)
    {
        nameOffsets.push_back(uint32_t(t.size()));
        t.insert(t.end(), e.name.begin(), e.name.end());
        t.push_back(0);
    }
    const uint32_t targetOffset = uint32_t(t.size());
    const char* target = isPixel ? "ps_3_0" : "vs_3_0";
    t.insert(t.end(), target, target + 7);
    const uint32_t creatorOffset = uint32_t(t.size());
    const char* creator = "xfb2xenos";
    t.insert(t.end(), creator, creator + 10);
    Align(t, 4);

    Set(t, 0x00, 0x1C);
    Set(t, 0x04, creatorOffset);
    Set(t, 0x08, isPixel ? 0xFFFF0300 : 0xFFFE0300);
    Set(t, 0x0C, uint32_t(entries.size()));
    Set(t, 0x10, infoOffset);
    Set(t, 0x14, 0);
    Set(t, 0x18, targetOffset);

    for (size_t i = 0; i < entries.size(); i++)
    {
        auto& e = entries[i];
        size_t p = infoOffset + i * 0x14;
        Set(t, p + 0x00, nameOffsets[i]);
        Set(t, p + 0x04, (uint32_t(e.set) << 16) | e.index);
        Set(t, p + 0x08, uint32_t(e.count) << 16);
        Set(t, p + 0x0C, e.set == 2 ? floatType : e.set == 3 ? samplerType : boolType);
        Set(t, p + 0x10, 0);
    }

    // D3DXSHADER_TYPEINFO: class, type, rows, columns, elements, structMembers, structMemberInfo
    auto type = [&](uint32_t at, uint16_t cls, uint16_t ty, uint16_t rows, uint16_t cols, uint16_t elements)
    {
        Set(t, at + 0, (uint32_t(cls) << 16) | ty);
        Set(t, at + 4, (uint32_t(rows) << 16) | cols);
        Set(t, at + 8, uint32_t(elements) << 16);
        Set(t, at + 12, 0);
    };
    type(floatType, 1 /* Vector */, 3 /* Float */, 1, 4, uint16_t(isPixel ? 224 : 256));
    type(samplerType, 4 /* Object */, 12 /* Sampler2D */, 1, 1, 1);
    type(boolType, 0 /* Scalar */, 1 /* Bool */, 1, 1, 1);
    return t;
}

// 2006 container header (0x18 bytes):
//   flags, virtualSize, physicalSize, definitionTableOffset (0 or 0x18), constantTableOffset, shaderOffset
// 2006 shader header (words): [0] ?, [1..3] ?, [4] interpolatorInfo, [5] 0, [6] ?, [7] PS outputs /
//   VS vertexElementCount, then PS: interpolators; VS: 3 words, vertex elements, interpolators.
static bool Convert(const std::vector<uint8_t>& d, size_t o, size_t microcode, std::vector<uint8_t>& out, Stats& stats)
{
    const uint32_t flags = Get(d, o);
    const uint32_t virtualSize = Get(d, o + 4);
    const uint32_t physicalSize = Get(d, o + 8);
    const uint32_t defOffset = Get(d, o + 0xC);
    const uint32_t ctabOffset = Get(d, o + 0x10);
    const uint32_t shaderOffset = Get(d, o + 0x14);
    const bool isPixel = (flags & 1) == 0;

    const bool hasTable = ctabOffset != 0;
    if (o + virtualSize > d.size() || microcode + physicalSize > d.size() || virtualSize > 0x10000 || physicalSize > 0x40000 ||
        shaderOffset == 0 || shaderOffset >= virtualSize || ctabOffset >= virtualSize ||
        (defOffset != 0 && hasTable && defOffset >= ctabOffset) || (defOffset != 0 && defOffset >= shaderOffset))
    {
        stats.skipped++;
        return false;
    }

    const size_t sh = o + shaderOffset;
    const uint32_t interpolatorInfo = Get(d, sh + 4 * 4);
    const uint32_t interpolatorCount = (interpolatorInfo >> 5) & 0x1F;
    const uint32_t word7 = Get(d, sh + 7 * 4);

    std::vector<uint8_t> c;
    c.reserve(virtualSize + physicalSize + 0x100);

    // 2008 container header, offsets patched below.
    for (int i = 0; i < 9; i++)
        Put(c, 0);

    // Constant table container: u32 size + CTAB (offsets inside the CTAB are relative to it).
    // Always the synthetic full-range table, even when the shader has its own: the renderer
    // uploads the whole constant range anyway, and a full table also covers registers a real table
    // leaves out (literal constants still win, see XenosRecomp's literalFloat4).
    const uint32_t ctabOut = uint32_t(c.size());
    {
        auto table = BuildSyntheticConstantTable(isPixel);
        Put(c, uint32_t(table.size()));
        c.insert(c.end(), table.begin(), table.end());
        if (!hasTable)
            stats.syntheticTables++;
    }
    Align(c, 4);

    // Definition table: 5-word header, float4 definitions (register | count, physical offset) until
    // 0, then int4 definitions until 0, then the rest (copied). Differences to the 2008 layout:
    // integer registers start at 0x22F0 instead of 0x2320, and 2008 entries carry one more word
    // after their values (XenosRecomp steps over 2 + count words).
    uint32_t defOut = 0;
    std::vector<uint8_t> literalData; // float literals moved to the physical part
    if (defOffset != 0)
    {
        const size_t srcStart = o + defOffset;
        const size_t srcEnd = o + (hasTable ? ctabOffset : shaderOffset);
        defOut = uint32_t(c.size());

        size_t p = srcStart;
        for (int i = 0; i < 5 && p + 4 <= srcEnd; i++, p += 4)
            Put(c, Get(d, p));

        while (p + 4 <= srcEnd && Get(d, p) != 0) // float4 definitions
        {
            Put(c, Get(d, p));
            Put(c, Get(d, p + 4));
            p += 8;
        }
        p += 4;

        // The 2006 second section holds float literals ("def c#") with their values inline:
        // { register | dword count, values... }. register >> 4 = 0x30 + absolute constant (VS c# = #,
        // PS c# = 256 + #); the compiler allocates them from the top: VS 0x12F0 = c255, PS 0x22C0 = c252.
        // 2008 float4 definitions point into the physical data instead, so the values are moved
        // after the microcode and the entries rewritten as float4 definitions.
        // The register is a byte offset into the D3D device's constant shadow (device + 0x400):
        // float constants from 0x300 (device 0x700 VS, 0x1700 PS), booleans at 0x2300 and loop
        // constants at 0x2320 + 4 * i (device 0x2720), which is also XenosRecomp's int4 encoding.
        std::vector<uint32_t> intDefs;
        while (p + 4 <= srcEnd && Get(d, p) != 0)
        {
            uint32_t w = Get(d, p);
            uint32_t reg = w >> 16, count = w & 0xFFFF;
            if (reg >= 0x2320 && reg < 0x23A0) // loop constants: { reg | count, values..., 0 }
            {
                intDefs.push_back(w);
                for (uint32_t i = 0; i < count; i++)
                    intDefs.push_back(Get(d, p + 4 + i * 4));
                intDefs.push_back(0);
                stats.loopDefs++;
                p += 4 + count * 4;
                continue;
            }
            if (reg < 0x300 || reg >= 0x2300)
            {
                printf("  unknown literal register 0x%04X (count %u) skipped\n", reg, count);
                p += 4 + count * 4;
                continue;
            }
            uint32_t absolute = (reg >> 4) - 0x30; // already includes the pixel shader base (256)
            Put(c, (absolute << 16) | count);
            Put(c, physicalSize + uint32_t(literalData.size()));
            for (uint32_t i = 0; i < count; i++)
            {
                uint32_t v = Get(d, p + 4 + i * 4);
                literalData.push_back(uint8_t(v >> 24));
                literalData.push_back(uint8_t(v >> 16));
                literalData.push_back(uint8_t(v >> 8));
                literalData.push_back(uint8_t(v));
            }
            while (literalData.size() % 16) // keep each literal 16-byte aligned (whole float4s)
                literalData.push_back(0);
            stats.intDefs++;
            p += 4 + count * 4;
        }
        Put(c, 0); // end of float4 definitions
        for (uint32_t v : intDefs)
            Put(c, v);
        Put(c, 0); // end of int4 definitions
        p += 4;

        for (; p + 4 <= srcEnd; p += 4) // remaining sections (unused by XenosRecomp)
            Put(c, Get(d, p));
    }
    Align(c, 4);

    // Shader header in the 2008 order.
    const uint32_t shaderOut = uint32_t(c.size());
    Put(c, 0);            // physicalOffset: microcode starts the physical part
    Put(c, physicalSize); // size
    Put(c, 0);            // field8

    uint32_t svPos = 0xFF; // none
    if (isPixel && (Get(d, sh + 2 * 4) & 0x08000000))
    {
        svPos = interpolatorCount; // VPOS: first register after the interpolators
        stats.vpos++;
    }
    Put(c, svPos << 8); // fieldC
    Put(c, 0);          // field10
    Put(c, interpolatorInfo);

    if (isPixel)
    {
        Put(c, 0);     // field18
        Put(c, word7); // outputs
        for (uint32_t i = 0; i < interpolatorCount; i++)
            Put(c, Get(d, sh + (8 + i) * 4));
        stats.pixel++;
    }
    else
    {
        const uint32_t elementCount = word7;
        Put(c, 3);            // field18: elements start 3 words into the array
        Put(c, elementCount); // vertexElementCount
        Put(c, 0);            // field20
        for (uint32_t i = 0; i < 3 + elementCount + interpolatorCount; i++)
            Put(c, Get(d, sh + (8 + i) * 4));
        stats.vertex++;
    }

    Align(c, 16);
    const uint32_t newVirtualSize = uint32_t(c.size());

    // Physical part (microcode and literal data), unchanged.
    c.insert(c.end(), d.begin() + microcode, d.begin() + microcode + physicalSize);
    c.insert(c.end(), literalData.begin(), literalData.end());

    Set(c, 0x00, 0x102A1100 | (flags & 0xFF));
    Set(c, 0x04, newVirtualSize);
    Set(c, 0x08, physicalSize + uint32_t(literalData.size()));
    Set(c, 0x10, ctabOut);
    Set(c, 0x14, defOut);
    Set(c, 0x18, shaderOut);
    // 0x0C, 0x1C, 0x20 stay 0 (XenosRecomp requires 0x1C/0x20 == 0)

    // The cache hash XenosRecomp gives this shader, and the key the runtime can compute when the
    // game creates the shader (it sees the 2006 container and the microcode, not this conversion).
    const uint64_t cacheHash = XXH3_64bits(c.data(), c.size());
    const uint64_t key = ShaderKey(d.data() + o, virtualSize, d.data() + microcode, physicalSize);
    g_keys.push_back({ key, cacheHash });

    if (g_listing)
    {
        fprintf(g_listing, "%016llX %s %s+0x%zX mc=0x%zX key=%016llX flags=%08X v=%X p=%X def=%X ctab=%X sh=%X |",
            (unsigned long long)cacheHash, isPixel ? "ps" : "vs", g_currentFile.c_str(), o, microcode, (unsigned long long)key,
            flags, virtualSize, physicalSize, defOffset, ctabOffset, shaderOffset);
        for (size_t w = sh; w + 4 <= o + virtualSize; w += 4)
            fprintf(g_listing, " %08X", Get(d, w));
        fprintf(g_listing, " | defs:");
        if (defOffset != 0)
            for (size_t w = o + defOffset; w + 4 <= o + (hasTable ? ctabOffset : shaderOffset); w += 4)
                fprintf(g_listing, " %08X", Get(d, w));
        fprintf(g_listing, "\n");
    }

    out.insert(out.end(), c.begin(), c.end());
    return true;
}

static void ConvertFile(const fs::path& in, const fs::path& outDir, Stats& stats)
{
    std::ifstream f(in, std::ios::binary);
    std::vector<uint8_t> d((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());

    std::vector<uint8_t> out;
    int found = 0;
    g_currentFile = in.filename().string();

    // XFB package, as the game's loader (sub_82770DC8) reads it:
    //   "\0XFB", u16 version (1), u16 groupCount, u32 parameterCount
    //   parameterCount x 8 bytes (parameter hash, type bytes)
    //   groupCount x 16 bytes { hash, virtualSize, physicalSize, (runtime pointer) }
    //   per group: virtual blob, then physical blob (all microcode of the group)
    // Virtual blob (offsets relative to its start): +0x08 pixel shader count, +0x0C vertex shader
    // count, +0x14 vertex shader record offsets, +0x18 pixel shader record offsets.
    // Record: { microcode offset in the physical blob, flags (low 7 bits: binding count),
    //   bindings[count] }, then the in-place D3D object (0x250 bytes VS, 0x38 PS; filled by
    //   sub_82452620 / sub_82452498), then the 2006 shader container.
    if (d.size() < 12 || Get(d, 0) != 0x00584642 || (Get(d, 4) >> 16) != 1)
    {
        printf("%-50s not an XFB package\n", in.filename().string().c_str());
        return;
    }
    const uint32_t groupCount = Get(d, 4) & 0xFFFF;
    const uint32_t parameterCount = Get(d, 8);
    size_t groupTable = 12 + size_t(parameterCount) * 8;
    size_t blob = groupTable + size_t(groupCount) * 16;
    for (uint32_t g = 0; g < groupCount; g++)
    {
        const uint32_t virtualSize = Get(d, groupTable + g * 16 + 4);
        const uint32_t physicalSize = Get(d, groupTable + g * 16 + 8);
        const size_t v = blob, p = blob + virtualSize;
        blob = p + physicalSize;
        if (blob > d.size())
        {
            printf("%-50s group %u out of range\n", in.filename().string().c_str(), g);
            break;
        }

        for (int kind = 0; kind < 2; kind++) // 0 = vertex, 1 = pixel
        {
            const uint32_t count = Get(d, v + (kind == 0 ? 0x0C : 0x08));
            const uint32_t array = Get(d, v + (kind == 0 ? 0x14 : 0x18));
            for (uint32_t i = 0; i < count; i++)
            {
                const size_t record = v + Get(d, v + array + i * 4);
                const uint32_t microcodeOffset = Get(d, record);
                const uint32_t bindings = Get(d, record + 4) & 0x7F;
                const size_t container = record + (bindings + 2) * 4 + (kind == 0 ? 0x250 : 0x38);
                const uint32_t flags = Get(d, container);
                if ((flags & 0xFFFFFF00) != 0x102A0E00 || ((flags & 1) == 0) != (kind == 1))
                {
                    printf("%-50s group %u %s %u: no container at 0x%zX\n", in.filename().string().c_str(), g,
                        kind == 0 ? "VS" : "PS", i, container);
                    stats.skipped++;
                    continue;
                }
                if (microcodeOffset + Get(d, container + 8) > physicalSize)
                {
                    printf("%-50s group %u %s %u: microcode outside the group\n", in.filename().string().c_str(), g,
                        kind == 0 ? "VS" : "PS", i);
                    stats.skipped++;
                    continue;
                }
                if (Convert(d, container, p + microcodeOffset, out, stats))
                    found++;
            }
        }
    }

    if (found)
    {
        fs::create_directories(outDir);
        std::ofstream(outDir / (in.filename().string() + ".xenos"), std::ios::binary).write((const char*)out.data(), out.size());
        printf("%-50s %3d shaders\n", in.filename().string().c_str(), found);
    }
}

int main(int argc, char** argv)
{
    if (argc < 3)
    {
        printf("Usage: xfb2xenos <output dir> <input file or dir>...\n");
        return 1;
    }

    Stats stats;
    fs::create_directories(argv[1]);
    g_listing = fopen((fs::path(argv[1]) / "listing.txt").string().c_str(), "w");
    for (int i = 2; i < argc; i++)
    {
        fs::path p = argv[i];
        if (fs::is_directory(p))
        {
            for (auto& e : fs::recursive_directory_iterator(p))
                if (e.is_regular_file())
                    ConvertFile(e.path(), argv[1], stats);
        }
        else
        {
            ConvertFile(p, argv[1], stats);
        }
    }

    printf("converted %d pixel + %d vertex shaders (%d use VPOS, %d float literal and %d loop constant definitions), skipped %d\n",
        stats.pixel, stats.vertex, stats.vpos, stats.intDefs, stats.loopDefs, stats.skipped);
    printf("constant tables synthesized for %d shaders\n", stats.syntheticTables);

    WriteKeyTable(fs::path(argv[1]) / "shader_keys.cpp");
    printf("%zu shader keys written to shader_keys.cpp\n", g_keys.size());

    // Two different shaders with the same key would make the runtime pick the wrong one.
    for (size_t i = 1; i < g_keys.size(); i++)
        if (g_keys[i].first == g_keys[i - 1].first)
            printf("warning: key %016llX maps to two cache entries\n", (unsigned long long)g_keys[i].first);
    return 0;
}
