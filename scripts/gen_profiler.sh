#!/bin/bash
# Generates runtime/src/profiler/call_profiler_gen.cpp: a counting wrapper for every recompiled
# function (overrides the weak sub_XXXXXXXX alias, then calls the real __imp__sub_XXXXXXXX).
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MAP="$ROOT/ppc/ppc_func_mapping.cpp"
OUT="$ROOT/runtime/src/profiler/call_profiler_gen.cpp"

grep -oE '\{ 0x[0-9A-F]+, sub_[0-9A-F]+ \}' "$MAP" | sed -E 's/\{ 0x([0-9A-F]+), (sub_[0-9A-F]+) \}/\1 \2/' > /tmp/dr_funcs.txt

# Functions the runtime already overrides (D3D hooks etc.) must not get a second wrapper.
grep -rhoE 'DR_D3D_TAP\(sub_[0-9A-F]+|GUEST_FUNCTION_HOOK\(sub_[0-9A-F]+' "$ROOT/runtime/src" --include=*.cpp \
  | grep -oE 'sub_[0-9A-F]+' | sort -u > /tmp/dr_hooked.txt || true
grep -vwFf /tmp/dr_hooked.txt /tmp/dr_funcs.txt > /tmp/dr_funcs_filtered.txt || true
mv /tmp/dr_funcs_filtered.txt /tmp/dr_funcs.txt
echo "Skipping $(wc -l < /tmp/dr_hooked.txt) functions the runtime hooks"
COUNT=$(wc -l < /tmp/dr_funcs.txt)

{
  echo "// Generated by scripts/gen_profiler.sh - do not edit."
  echo "#include \"call_profiler.h\""
  echo ""
  echo "const uint32_t CallProfiler::kFunctionCount = $COUNT;"
  echo "const uint32_t CallProfiler::kFunctionAddresses[$COUNT] = {"
  awk '{ printf "    0x%s,\n", $1 }' /tmp/dr_funcs.txt
  echo "};"
  echo ""
  awk '{ printf "PPC_FUNC_IMPL(__imp__%s);\nPPC_FUNC(%s) { int s = CallProfiler::Record(%d, ctx); __imp__%s(ctx, base); CallProfiler::Return(%d, s, ctx); }\n", $2, $2, NR - 1, $2, NR - 1 }' /tmp/dr_funcs.txt
} > "$OUT"

echo "Wrote $COUNT wrappers to $OUT"
