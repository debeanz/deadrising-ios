# Compiles the renderer's own shaders (runtime/src/gpu/blit.hlsl) to SPIR-V and writes
# runtime/src/gpu/blit_spirv.h, so the Vulkan path (Windows with DR_GPU=vulkan, iOS through
# MoltenVK) needs no shader compiler at runtime. Rerun after editing blit.hlsl.
# Works with Windows PowerShell and PowerShell 7 (pwsh on the macOS build runner): set DXC to the
# dxc binary there.
param([string]$Dxc = $env:DXC)
$root = Split-Path -Parent $PSScriptRoot
if (-not $Dxc) { $Dxc = Join-Path $root "tools\XenosRecomp\thirdparty\dxc-bin\bin\x64\dxc.exe" }
$src = Join-Path $root "runtime\src\gpu\blit.hlsl"
$out = Join-Path $root "runtime\src\gpu\blit_spirv.h"
$tmp = [System.IO.Path]::GetTempPath()

$entries = @(
    @{ Name = "mainVS"; Profile = "vs_6_0"; Extra = @("-fvk-invert-y") },
    @{ Name = "mainPS"; Profile = "ps_6_0"; Extra = @() },
    @{ Name = "mainDepthPS"; Profile = "ps_6_0"; Extra = @() },
    @{ Name = "mainDepthMsaaPS"; Profile = "ps_6_0"; Extra = @() },
    @{ Name = "mainOverlayPS"; Profile = "ps_6_0"; Extra = @() },
    @{ Name = "mainMenuPS"; Profile = "ps_6_0"; Extra = @() },
    @{ Name = "mainEncode7e3PS"; Profile = "ps_6_0"; Extra = @() }
)

$lines = @("// Generated by scripts/build_blit_spirv.ps1 from blit.hlsl - do not edit.", "#pragma once", "#include <cstdint>", "")
foreach ($e in $entries) {
    $spv = Join-Path $tmp ("dr_blit_" + $e.Name + ".spv")
    $args = @("-E", $e.Name, "-T", $e.Profile, "-HV", "2021", "-spirv", "-fvk-use-dx-layout") + $e.Extra + @("-Fo", $spv, $src)
    & $Dxc @args
    if ($LASTEXITCODE -ne 0) { throw "dxc failed for $($e.Name)" }
    $bytes = [System.IO.File]::ReadAllBytes($spv)
    $lines += "inline const uint8_t kBlitSpirv_$($e.Name)[] = {"
    for ($i = 0; $i -lt $bytes.Length; $i += 24) {
        $chunk = $bytes[$i..([Math]::Min($i + 23, $bytes.Length - 1))] | ForEach-Object { "0x{0:X2}," -f $_ }
        $lines += "    " + ($chunk -join "")
    }
    $lines += "};"
    $lines += ""
    Remove-Item $spv
}
[System.IO.File]::WriteAllLines($out, $lines)
Write-Output "wrote $out"
